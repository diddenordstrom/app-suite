// Build docs/index.md from the frontmatter of every page under docs/, and lint the wiki.
//   node scripts/docs-index.mjs          write docs/index.md
//   node scripts/docs-index.mjs --check  fail if the index is stale or a page breaks the rules (CI)
// No dependencies, Node 22 only. The index is generated so parallel sessions never conflict on it.
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const DOCS = "docs";
const INDEX = `${DOCS}/index.md`;
const TYPES = ["decision", "app", "note", "research"];
const LOG_KINDS = ["ingest", "decision", "query", "lint", "note"];
const REQUIRED = ["title", "summary", "type", "updated"];
const RECENT = 8;

const check = process.argv.includes("--check");
const errors = [];
const out = (s) => process.stdout.write(`${s}\n`);

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.posix.join(dir, e.name);
    return e.isDirectory() ? walk(p) : [p];
  });
const read = (f) => fs.readFileSync(f, "utf8").replace(/\r\n/g, "\n");

function frontmatter(text) {
  const m = /^---\n([\s\S]*?)\n---\n?/.exec(text);
  if (!m) return null;
  const data = {};
  for (const line of m[1].split("\n")) {
    const kv = /^([A-Za-z_-]+):\s*(.*)$/.exec(line);
    if (kv) data[kv[1]] = kv[2].replace(/^["']|["']$/g, "").trim();
  }
  return data;
}

const all = walk(DOCS).sort();
const markdown = all.filter((f) => f.endsWith(".md") && f !== INDEX);
const logs = markdown.filter((f) => f.startsWith(`${DOCS}/log/`));
const raw = all.filter(
  (f) => f.startsWith(`${DOCS}/raw/`) && !/\/(README\.md|\.gitkeep)$/.test(f),
);
const pages = markdown.filter(
  (f) => f !== `${DOCS}/CLAUDE.md` && !f.startsWith(`${DOCS}/log/`) && !f.startsWith(`${DOCS}/raw/`),
);

// Pages: frontmatter is the index entry, so it has to be complete.
const entries = pages.flatMap((file) => {
  const fm = frontmatter(read(file));
  if (!fm) {
    errors.push(`${file}: missing frontmatter (title, summary, type, updated)`);
    return [];
  }
  for (const key of REQUIRED) if (!fm[key]) errors.push(`${file}: frontmatter needs "${key}"`);
  if (fm.type && !TYPES.includes(fm.type)) errors.push(`${file}: type "${fm.type}" must be one of ${TYPES.join(", ")}`);
  if (fm.updated && !/^\d{4}-\d{2}-\d{2}$/.test(fm.updated)) errors.push(`${file}: updated must be YYYY-MM-DD`);
  return [{ file, ...fm }];
});

// Log: append-only, one heading per event, so `grep "^## \[" docs/log/*.md | tail` works.
const logLine = new RegExp(`^## \\[(\\d{4}-\\d{2}-\\d{2})\\] (${LOG_KINDS.join("|")}) \\| (\\S.*)$`);
const events = logs.flatMap((file) =>
  read(file)
    .split("\n")
    .filter((l) => l.startsWith("## ["))
    .flatMap((l) => {
      const m = logLine.exec(l);
      if (!m) {
        errors.push(`${file}: log heading must be "## [YYYY-MM-DD] ${LOG_KINDS.join("|")} | Title": ${l}`);
        return [];
      }
      return [{ date: m[1], kind: m[2], title: m[3], file }];
    }),
);

// Relative links must resolve (code fences are ignored).
for (const file of markdown) {
  const text = read(file).replace(/```[\s\S]*?```/g, "");
  for (const m of text.matchAll(/\]\(([^)\s]+)\)/g)) {
    const target = m[1].split("#")[0];
    if (!target || /^[a-z][a-z0-9+.-]*:/i.test(target)) continue;
    const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(file), target));
    if (!fs.existsSync(resolved)) errors.push(`${file}: broken link ${m[1]}`);
  }
}

const rel = (f) => path.posix.relative(DOCS, f);
const groups = new Map();
for (const e of entries) {
  const dir = path.posix.dirname(rel(e.file));
  const key = dir === "." ? "top level" : dir;
  groups.set(key, [...(groups.get(key) ?? []), e]);
}

const lines = [
  "# Docs index",
  "",
  "> Generated by `npm run docs:index` from page frontmatter. Do not edit by hand. Read this first, then open only the pages you need. Conventions: [CLAUDE.md](CLAUDE.md).",
  "",
  "## Recent activity",
  "",
  ...(events.length
    ? events.slice(-RECENT).reverse().map((e) => `- ${e.date} · ${e.kind} · ${e.title} ([${rel(e.file)}](${rel(e.file)}))`)
    : ["Nothing logged yet."]),
  "",
  "## Pages",
  "",
  ...(entries.length
    ? [...groups.keys()].sort().flatMap((key) => [
        `### ${key}`,
        "",
        ...groups.get(key).map((e) => {
          const meta = [e.type, e.status, e.updated].filter(Boolean).join(" · ");
          return `- [${e.title}](${rel(e.file)}): ${e.summary} _(${meta})_`;
        }),
        "",
      ])
    : ["No pages yet.", ""]),
  "## Raw sources",
  "",
  ...(raw.length ? raw.map((f) => `- [${rel(f)}](${rel(f)})`) : ["None yet."]),
  "",
];
const next = lines.join("\n");

if (errors.length) {
  process.stderr.write(errors.map((e) => `docs: ${e}\n`).join(""));
  process.exit(1);
}

const current = fs.existsSync(INDEX) ? read(INDEX) : "";
if (check) {
  if (current !== next) {
    process.stderr.write(`docs: ${INDEX} is stale, run "npm run docs:index" and commit it\n`);
    process.exit(1);
  }
  out(`docs: ok (${entries.length} pages, ${events.length} log entries)`);
} else {
  if (current !== next) fs.writeFileSync(INDEX, next);
  out(`docs: ${current === next ? "index unchanged" : `wrote ${INDEX}`} (${entries.length} pages, ${events.length} log entries)`);
}
